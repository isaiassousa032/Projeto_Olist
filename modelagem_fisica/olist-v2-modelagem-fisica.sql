CREATE TABLE IF NOT EXISTS "CUSTOMERS" (
	"customer_id" VARCHAR(32) NOT NULL,
	-- Identifica a pessoa entre compras; nao e unico nesta tabela.
	"customer_unique_id" VARCHAR(32) NOT NULL,
	"customer_zip_code_prefix" VARCHAR(5) NOT NULL,
	"customer_city" VARCHAR(255),
	"customer_state" CHAR(2),
	PRIMARY KEY("customer_id")
);

COMMENT ON COLUMN "CUSTOMERS"."customer_unique_id" IS 'Identifica a pessoa entre compras; nao e unico nesta tabela.';

CREATE INDEX "ix_customers_unique_id"
ON "CUSTOMERS" ("customer_unique_id");
CREATE INDEX "ix_customers_zip"
ON "CUSTOMERS" ("customer_zip_code_prefix");

CREATE TABLE IF NOT EXISTS "ORDERS" (
	"order_id" VARCHAR(32) NOT NULL,
	"customer_id" VARCHAR(32) NOT NULL,
	"order_status" VARCHAR(20) NOT NULL,
	"order_purchase_timestamp" TIMESTAMP NOT NULL,
	"order_approved_at" TIMESTAMP,
	"order_delivered_carrier_date" TIMESTAMP,
	"order_delivered_customer_date" TIMESTAMP,
	"order_estimated_delivery_date" TIMESTAMP,
	PRIMARY KEY("order_id")
);

COMMENT ON TABLE "ORDERS" IS 'Datas da fonte sem fuso explicito: preservadas como timestamp. Datas de aprovacao e entrega podem estar ausentes.';

CREATE INDEX "ix_orders_customer"
ON "ORDERS" ("customer_id");
CREATE INDEX "ix_orders_purchase"
ON "ORDERS" ("order_purchase_timestamp");

CREATE TABLE IF NOT EXISTS "ORDER_ITEMS" (
	"order_id" VARCHAR(32) NOT NULL,
	"order_item_id" INTEGER NOT NULL CHECK(order_item_id > 0),
	"product_id" VARCHAR(32) NOT NULL,
	"seller_id" VARCHAR(32) NOT NULL,
	"shipping_limit_date" TIMESTAMP,
	"price" NUMERIC(12,2) NOT NULL CHECK(price >= 0),
	"freight_value" NUMERIC(12,2) NOT NULL CHECK(freight_value >= 0),
	PRIMARY KEY("order_id", "order_item_id")
);

COMMENT ON TABLE "ORDER_ITEMS" IS 'Uma linha por item sequencial do pedido. Valores monetarios em BRL. price e freight_value devem ser >= 0; order_item_id > 0.';

CREATE INDEX "ix_order_items_product"
ON "ORDER_ITEMS" ("product_id");
CREATE INDEX "ix_order_items_seller"
ON "ORDER_ITEMS" ("seller_id");

CREATE TABLE IF NOT EXISTS "SELLERS" (
	"seller_id" VARCHAR(32) NOT NULL,
	"seller_zip_code_prefix" VARCHAR(5),
	"seller_city" VARCHAR(255),
	"seller_state" CHAR(2),
	PRIMARY KEY("seller_id")
);

CREATE INDEX "ix_sellers_zip"
ON "SELLERS" ("seller_zip_code_prefix");

CREATE TABLE IF NOT EXISTS "PRODUCTS" (
	"product_id" VARCHAR(32) NOT NULL,
	"product_category_name" VARCHAR(255),
	"product_name_lenght" INTEGER CHECK(product_name_lenght >= 0),
	"product_description_lenght" INTEGER CHECK(product_description_lenght >= 0),
	"product_photos_qty" INTEGER CHECK(product_photos_qty >= 0),
	"product_weight_g" INTEGER CHECK(product_weight_g >= 0),
	"product_length_cm" INTEGER CHECK(product_length_cm >= 0),
	"product_height_cm" INTEGER CHECK(product_height_cm >= 0),
	"product_width_cm" INTEGER CHECK(product_width_cm >= 0),
	PRIMARY KEY("product_id")
);

COMMENT ON TABLE "PRODUCTS" IS 'Campos lenght mantidos conforme CSV original. Atributos descritivos podem ser nulos. Medidas e contagens nao negativas quando informadas.';

CREATE INDEX "ix_products_category"
ON "PRODUCTS" ("product_category_name");

CREATE TABLE IF NOT EXISTS "GEOLOCATION" (
	"geolocation_id" BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
	"geolocation_zip_code_prefix" VARCHAR(5) NOT NULL,
	"geolocation_lat" NUMERIC(22,18) CHECK(geolocation_lat BETWEEN -90 AND 90),
	"geolocation_lng" NUMERIC(22,18) CHECK(geolocation_lng BETWEEN -180 AND 180),
	"geolocation_city" VARCHAR(255),
	"geolocation_state" CHAR(2),
	PRIMARY KEY("geolocation_id")
);

COMMENT ON TABLE "GEOLOCATION" IS 'Uma linha da fonte geografica. PK tecnica gerada na carga. Prefixo de CEP pode se repetir: nao usar como PK nem destino de FK. Para cruzar clientes/vendedores, primeiro consolidar uma linha por prefixo com regra geografica documentada. Latitude entre -90 e 90; longitude entre -180 e 180.';

CREATE INDEX "ix_geolocation_zip"
ON "GEOLOCATION" ("geolocation_zip_code_prefix");

CREATE TABLE IF NOT EXISTS "PRODUCT_CATEGORY_NAME_TRANSLATION" (
	"product_category_name" VARCHAR(255) NOT NULL,
	"product_category_name_english" VARCHAR(255),
	PRIMARY KEY("product_category_name")
);

COMMENT ON TABLE "PRODUCT_CATEGORY_NAME_TRANSLATION" IS 'Catalogo de categorias. Antes de carregar PRODUCTS, incluir categorias presentes em produtos mas ausentes na traducao, deixando ingles NULL. Nao inventar traducao.';

CREATE TABLE IF NOT EXISTS "ORDER_REVIEWS" (
	"review_row_id" BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
	"review_id" VARCHAR(32) NOT NULL,
	"order_id" VARCHAR(32) NOT NULL,
	"review_score" SMALLINT NOT NULL CHECK(review_score BETWEEN 1 AND 5),
	"review_comment_title" TEXT,
	"review_comment_message" TEXT,
	"review_creation_date" TIMESTAMP,
	"review_answer_timestamp" TIMESTAMP,
	PRIMARY KEY("review_row_id")
);

COMMENT ON TABLE "ORDER_REVIEWS" IS 'PK tecnica preserva linhas sem presumir unicidade do review_id. Um pedido pode ter mais de uma avaliacao. Score de 1 a 5. Reprocessar via staging para evitar duplicar linhas.';

CREATE INDEX "ix_order_reviews_review"
ON "ORDER_REVIEWS" ("review_id");
CREATE INDEX "ix_order_reviews_order"
ON "ORDER_REVIEWS" ("order_id");

CREATE TABLE IF NOT EXISTS "ORDER_PAYMENTS" (
	"order_id" VARCHAR(32) NOT NULL,
	"payment_sequential" INTEGER NOT NULL CHECK(payment_sequential > 0),
	"payment_type" VARCHAR(30) NOT NULL,
	"payment_installments" INTEGER NOT NULL CHECK(payment_installments >= 0),
	"payment_value" NUMERIC(12,2) NOT NULL CHECK(payment_value >= 0),
	PRIMARY KEY("order_id", "payment_sequential")
);

COMMENT ON TABLE "ORDER_PAYMENTS" IS 'Uma linha por sequencia de pagamento do pedido. payment_sequential > 0; payment_installments >= 0; payment_value >= 0. Preservar valores zero existentes na fonte.';

